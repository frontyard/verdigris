#!/usr/bin/env python3
"""Render the schemars JSON schema (`verd schema`) into reference.md.

Usage: verd schema | python3 docs/gen-reference.py > docs/book/src/reference.md
Sections follow the schema definition order; each struct becomes a table
of field / type / default / description rows.
"""
import json
import sys

SCHEMA = json.load(sys.stdin)
DEFS = SCHEMA.get("$defs") or SCHEMA.get("definitions") or {}

ORDER = [
    "Config", "ServerConfig", "ListenAddr", "Limits", "Timeouts",
    "LogConfig", "LogLimits", "AccessLog", "AdminConfig", "ManualTls",
    "AcmeConfig", "SiteConfig", "SiteTls", "TlsMode", "AutoTls",
    "OnDemandTls", "RouteConfig", "RouteMatch", "RouteLimits",
    "RouteTimeouts", "StaticHandler", "RespondHandler", "RedirectHandler",
    "ProxyHandler", "Rewrite", "UpstreamConfig", "UpstreamRef",
    "HealthCheck", "ActiveHealth", "PassiveHealth", "RetryPolicy",
    "UnavailableConfig", "AuthConfig", "BasicAuth", "BasicUser",
    "BearerAuth", "ApiKeyAuth", "CorsConfig", "RateLimitConfig",
    "HeaderOps", "SecurityConfig", "RouteSecurity", "CompressConfig",
    "RouteCache", "CacheBypass", "CacheStore", "Include", "IpAcl",
]


def type_name(prop):
    if "$ref" in prop:
        return prop["$ref"].rsplit("/", 1)[-1]
    for k in ("allOf", "oneOf", "anyOf"):
        if k in prop:
            return " \\| ".join(type_name(p) for p in prop[k])
    t = prop.get("type")
    if t == "array":
        return f"[{type_name(prop.get('items', {}))}]"
    if isinstance(t, list):
        return " \\| ".join(t)
    return t or "any"


def fmt_default(prop):
    if "default" not in prop:
        return ""
    return f"`{json.dumps(prop['default'])}`"


def member_form(prop):
    """A one-cell label for a `oneOf`/`anyOf` member."""
    if "const" in prop:
        return f"`{json.dumps(prop['const'])}`"
    if "$ref" in prop:
        return f"`{prop['$ref'].rsplit('/', 1)[-1]}` table"
    t = prop.get("type")
    if t == "object":
        keys = ", ".join(prop.get("properties") or {})
        return f"`{{ {keys} }}`" if keys else "`{ … }`"
    if t == "array":
        return "`[…]`"
    if isinstance(t, list):
        return " \\| ".join(t)
    return f"`{t}`" if t else "`any`"


def section(name):
    d = DEFS.get(name)
    if not d:
        return ""
    desc = (d.get("description") or "").strip()
    out = [f"\n## `{name}`\n"]
    if desc:
        out.append(desc + "\n")
    props = d.get("properties") or {}
    req = set(d.get("required") or [])
    if props:
        out.append("| field | type | default | description |")
        out.append("|---|---|---|---|")
        for fname, prop in props.items():
            pdesc = (prop.get("description") or "").replace("\n", " ").strip()
            r = " **required**" if fname in req else ""
            out.append(
                f"| `{fname}` | {type_name(prop)}{r} | {fmt_default(prop)} | {pdesc} |"
            )
        return "\n".join(out)
    # unions and enums carry no `properties` — render accepted forms so
    # the section isn't a bare heading (lb, tls, tier, format, …)
    members = d.get("oneOf") or d.get("anyOf") or []
    if members:
        out.append("| form | description |")
        out.append("|---|---|")
        for p in members:
            pdesc = (p.get("description") or "").replace("\n", " ").strip()
            out.append(f"| {member_form(p)} | {pdesc} |")
    elif "enum" in d:
        out.append("| value |")
        out.append("|---|")
        for v in d["enum"]:
            out.append(f"| `{json.dumps(v)}` |")
    return "\n".join(out)


print("<!-- GENERATED by docs/gen-reference.py — do not edit by hand. -->\n")
print("# Configuration reference\n")
print("Every field verd accepts in `verd.toml`, generated from the")
print("JSON Schema (`verd schema`). Durations accept `500ms`, `10s`,")
print("`5m`, `1h`, `1d`; sizes accept `B`, `KiB`, `MiB`, `GiB`.\n")
# the root schema object *is* `Config`
DEFS.setdefault("Config", SCHEMA)

seen = set()
for name in ORDER + sorted(set(DEFS) - set(ORDER)):
    if name not in seen:
        print(section(name))
        seen.add(name)
